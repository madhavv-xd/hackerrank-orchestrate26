// Writes evaluation/usage_report.md from the run's LLM ledger. Costs come only from llm.ts PRICES; never estimated.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT } from "./load.ts";
import { PRICES, type LedgerEntry } from "./llm.ts";

export function writeUsageReport(entries: LedgerEntry[], requests: number, run: { runId: string; gitSha: string; fallbackIntents: number }) {
  const live = entries.filter((e) => !e.cached);
  const rows = new Map<string, { calls: number; cached: number; input: number; output: number; cost: number | null }>();
  for (const e of entries) {
    const k = `${e.provider} | ${e.model} | ${e.purpose}`;
    const r = rows.get(k) ?? { calls: 0, cached: 0, input: 0, output: 0, cost: 0 };
    if (e.cached) r.cached++; else r.calls++;
    r.input += e.inputTokens; r.output += e.outputTokens;
    r.cost = r.cost === null || e.costUsd === null ? null : r.cost + e.costUsd;
    rows.set(k, r);
  }
  const tin = live.reduce((a, e) => a + e.inputTokens, 0), tout = live.reduce((a, e) => a + e.outputTokens, 0);
  const cost = live.reduce((a, e) => a + (e.costUsd ?? 0), 0);
  const md = `# Usage report — final full-dataset run

Generated by \`npm run audit\` (run \`${run.runId}\`, git \`${run.gitSha.slice(0, 12)}\`) for the ${requests} requests in
\`dataset/deletion_requests.csv\` (the 32 labelled samples are audited in the same run because they share the activity ledger).

## Totals

| Metric | Value |
|---|---|
| Live model calls | ${live.length} |
| Cache hits (no API call) | ${entries.length - live.length} |
| Input tokens | ${tin} |
| Output tokens | ${tout} |
| Total tokens | ${tin + tout} |
| Average tokens per request | ${(requests ? (tin + tout) / requests : 0).toFixed(2)} |
| Estimated total cost (USD) | ${cost.toFixed(4)} |
| Estimated cost per request (USD) | ${(requests ? cost / requests : 0).toFixed(6)} |
| Requests whose intent came from the deterministic fallback | ${run.fallbackIntents} |

## Per provider / model / purpose

| Provider | Model | Purpose | Live calls | Cache hits | Input tokens | Output tokens | Cost (USD) |
|---|---|---|---|---|---|---|---|
${[...rows].map(([k, r]) => `| ${k.split(" | ").join(" | ")} | ${r.calls} | ${r.cached} | ${r.input} | ${r.output} | ${r.cost === null ? "n/a (no price)" : r.cost.toFixed(4)} |`).join("\n") || "| — | — | — | 0 | 0 | 0 | 0 | 0 |"}

Prices used (USD per 1M tokens, from \`code/src/llm.ts\`): ${Object.entries(PRICES).map(([m, p]) => `${m} ${p.input}/${p.output}`).join("; ") || "none configured (only \`:free\` models used)"}.

## Notes

- \`manual-transcription\` rows are the 11 screenshots read by the coding agent used to build this project while
  building the solution, stored in the vision cache slot because no API key was available. They cost nothing at
  run time and are **not** model calls of this run.
- OpenRouter \`:free\` models are recorded at cost 0; a paid model is priced from \`PRICES\` in \`code/src/llm.ts\`.
- With a provider configured, intent classification (one call per distinct request text), screenshot extraction
  (cache miss only) and the investigator agent (only for tied ledger attributions) call the configured model; every
  response is cached under \`code/cache/llm/\`, so a rerun makes zero calls.
- Results of the earlier live OpenRouter development runs (tokens, latency, accuracy) are in
  \`evaluation_report.md\` §6.
`;
  writeFileSync(join(REPO_ROOT, "code", "evaluation", "usage_report.md"), md);
}
